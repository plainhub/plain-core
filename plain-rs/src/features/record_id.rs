use std::time::{SystemTime, UNIX_EPOCH};
use uuid::Uuid;

pub fn generate() -> String {
    let millis = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .expect("System clock precedes Unix epoch")
        .as_millis() as u64;
    from_unix_millis(millis).to_string()
}

fn from_unix_millis(millis: u64) -> Uuid {
    let mut bytes = *Uuid::new_v4().as_bytes();
    bytes[..6].copy_from_slice(&millis.to_be_bytes()[2..]);
    bytes[6] = (bytes[6] & 0x0f) | 0x70;
    Uuid::from_bytes(bytes)
}

pub fn typescript_source() -> &'static str {
    r#"// Generated by plain-core identity_sources; do not edit.
import { bytesToHex } from '@/lib/strutil'

export function generateRecordId(): string {
  const bytes = crypto.getRandomValues(new Uint8Array(16))
  let millis = Date.now()
  for (let i = 5; i >= 0; i--) {
    bytes[i] = millis % 256
    millis = Math.floor(millis / 256)
  }
  bytes[6] = (bytes[6] & 0x0f) | 0x70
  bytes[8] = (bytes[8] & 0x3f) | 0x80
  const hex = bytesToHex(bytes)
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`
}
"#
}

