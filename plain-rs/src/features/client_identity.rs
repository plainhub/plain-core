use plain_libs::utils::uuid::Uuid;

pub const DISCOVERY_UUID: &str = "706c6169-0000-8000-8000-000000000000";
pub const DISCOVERY_UUID_MASK: &str = "ffffffff-0000-f000-c000-000000000000";

pub fn generate() -> String {
    let mut bytes = *Uuid::new_v4().as_bytes();
    bytes[..4].copy_from_slice(b"plai");
    bytes[6] = (bytes[6] & 0x0f) | 0x80;
    Uuid::from_bytes(bytes).into_string()
}

pub fn is_valid(value: &str) -> bool {
    value.len() == 36 && Uuid::parse_str(value).is_ok_and(|id| id.into_string() == value)
}

pub fn parse(value: &str) -> Option<Uuid> {
    let uuid = Uuid::parse_str(value).ok()?;
    let bytes = uuid.as_bytes();
    (bytes[..4] == *b"plai" && bytes[6] >> 4 == 8 && bytes[8] & 0xc0 == 0x80).then_some(uuid)
}

pub fn typescript_source() -> String {
    let prefix = Uuid::parse_str(DISCOVERY_UUID).unwrap();
    let mask = Uuid::parse_str(DISCOVERY_UUID_MASK).unwrap();
    format!(
        r#"// Generated by plain-core identity_sources; do not edit.
import {{ bytesToHex }} from '@/lib/strutil'

const prefix = {prefix:?}
const mask = {mask:?}

export function generateClientId(): string {{
  const bytes = crypto.getRandomValues(new Uint8Array(16))
  for (let i = 0; i < bytes.length; i++) bytes[i] = (bytes[i] & ~mask[i]) | prefix[i]
  const hex = bytesToHex(bytes)
  return `${{hex.slice(0, 8)}}-${{hex.slice(8, 12)}}-${{hex.slice(12, 16)}}-${{hex.slice(16, 20)}}-${{hex.slice(20)}}`
}}
"#,
        prefix = prefix.as_bytes(),
        mask = mask.as_bytes()
    )
}

