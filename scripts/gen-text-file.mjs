import { readFileSync, writeFileSync } from 'node:fs'

const source = readFileSync(new URL('../plain-libs/src/utils/text_file.rs', import.meta.url), 'utf8')

function readList(name) {
  const match = source.match(new RegExp(`const ${name}: &\\[&str\\] = &\\[([^\\]]*)\\];`))
  if (!match) throw new Error(`Missing ${name} in text_file.rs`)
  return JSON.parse(`[${match[1].trim().replace(/,$/, '')}]`)
}

function renderList(values, quote, indent) {
  const rows = []
  for (let i = 0; i < values.length; i += 8) {
    const valuesInRow = values.slice(i, i + 8).map(value => `${quote}${value}${quote},`)
    rows.push(' '.repeat(indent) + valuesInRow.join(' '))
  }
  return rows.join('\n')
}

const extensions = readList('TEXT_FILE_EXTENSIONS')
const names = readList('TEXT_FILE_NAMES')
const banner = '// Generated by plain-core/scripts/gen-text-file.mjs.\n'
const outputs = [
  ['../../plain-desktop/src/lib/text-file.generated.ts', `${banner}
const extensions = new Set([
${renderList(extensions, "'", 2)}
])

const names = new Set([
${renderList(names, "'", 2)}
])

export function isTextFile(path: string): boolean {
  const name = path.slice(Math.max(path.lastIndexOf('/'), path.lastIndexOf('\\\\')) + 1).toLowerCase()
  const dot = name.lastIndexOf('.')
  return names.has(name) || (dot >= 0 && extensions.has(name.slice(dot + 1)))
}
`],
  ['../../plain-app/plain-common/src/commonMain/kotlin/com/ismartcoding/plain/lib/extensions/TextFile.generated.kt', `${banner}package com.ismartcoding.plain.lib.extensions

private val textFileExtensions = setOf(
${renderList(extensions, '"', 4)}
)

private val textFileNames = setOf(
${renderList(names, '"', 4)}
)

internal fun isTextFileName(path: String): Boolean {
    val name = path.substring(maxOf(path.lastIndexOf('/'), path.lastIndexOf('\\\\')) + 1).lowercase()
    return name in textFileNames || name.substringAfterLast('.', "") in textFileExtensions
}
`],
]

for (const [path, content] of outputs) {
  const file = new URL(path, import.meta.url)
  if (process.argv.includes('--write')) writeFileSync(file, content)
  else if (readFileSync(file, 'utf8') !== content) throw new Error(`Stale generated text file matcher: ${file.pathname}`)
}
