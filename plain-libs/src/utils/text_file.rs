pub fn is_text_file(path: &str) -> bool {
    let name = path
        .rsplit(['/', '\\'])
        .next()
        .unwrap_or_default()
        .to_lowercase();
    TEXT_FILE_NAMES.contains(&name.as_str())
        || name
            .rsplit_once('.')
            .is_some_and(|(_, extension)| TEXT_FILE_EXTENSIONS.contains(&extension))
}
