use std::{fmt, io};

#[derive(Debug)]
pub enum Error {
    InvalidFormat(&'static str),
    Io(io::Error),
    NotFound(&'static str),
    NotSupported(&'static str),
}

impl From<io::Error> for Error {
    fn from(error: io::Error) -> Self {
        Self::Io(error)
    }
}

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidFormat(message) | Self::NotSupported(message) => f.write_str(message),
            Self::Io(error) => error.fmt(f),
            Self::NotFound(container) => write!(f, "No Exif data found in {}", container),
        }
    }
}
