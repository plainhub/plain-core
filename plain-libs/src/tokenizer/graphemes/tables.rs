mod util {
    #[inline]
    pub fn bsearch_range_table(c: char, r: &[(char, char)]) -> bool {
        use core::cmp::Ordering::{Equal, Greater, Less};
        r.binary_search_by(|&(lo, hi)| {
            if lo <= c && c <= hi {
                Equal
            } else if hi < c {
                Less
            } else {
                Greater
            }
        })
        .is_ok()
    }
}

